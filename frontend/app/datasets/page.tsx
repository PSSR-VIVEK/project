"use client"
import { useEffect, useState } from 'react';
import { motion } from 'framer-motion';
import { Database, HardDrive, FileSpreadsheet, Loader2, XCircle } from 'lucide-react';
import { Card, CardHeader, CardTitle, CardContent, CardDescription } from '@/components/ui/card';
import { api } from '@/services/api';
import { DatasetsResponse } from '@/types/api';

export default function DatasetsPage() {
  const [data, setData] = useState<DatasetsResponse | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    async function fetchDatasets() {
      try {
        const response = await api.getDatasets();
        setData(response);
      } catch (err) {
        setError("Failed to fetch datasets from backend.");
      } finally {
        setLoading(false);
      }
    }
    fetchDatasets();
  }, []);

  if (loading) {
    return (
      <div className="flex h-full items-center justify-center">
        <Loader2 className="w-8 h-8 animate-spin text-primary" />
      </div>
    );
  }

  if (error || !data) {
    return (
      <div className="flex h-full items-center justify-center text-destructive">
        <XCircle className="w-6 h-6 mr-2" /> {error || "No data available"}
      </div>
    );
  }

  const datasetEntries = Object.entries(data.datasets);

  return (
    <div className="max-w-5xl mx-auto space-y-8 pb-12">
      <div>
        <h1 className="text-3xl font-bold tracking-tight">Dataset Explorer</h1>
        <p className="text-muted-foreground mt-1">Processed feature matrices for inference.</p>
      </div>

      <Card className="bg-card/50 backdrop-blur border-primary/20 mb-6">
        <CardHeader>
          <CardTitle>About the Datasets</CardTitle>
          <CardDescription>Understanding the multimodal inputs used for inference.</CardDescription>
        </CardHeader>
        <CardContent className="text-muted-foreground text-sm space-y-4 leading-relaxed">
          <p>
            This project relies on a <strong>multimodal fusion</strong> approach, combining spatial and temporal datasets to accurately predict climate extremes like flash floods and heat waves.
          </p>
          <ul className="list-disc pl-5 space-y-2">
            <li>
              <strong className="text-foreground">CNN Features (Spatial):</strong> Extracted from ResNet18, these matrices represent the visual and spatial embeddings of high-resolution satellite imagery, capturing topography and geography.
            </li>
            <li>
              <strong className="text-foreground">Transformer Features (Temporal):</strong> Sequence embeddings generated by our Weather Transformer Encoder. These represent meteorological time-series data (e.g., temperature, precipitation, and soil moisture).
            </li>
          </ul>
        </CardContent>
      </Card>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
        {datasetEntries.map(([name, info], idx) => (
          <motion.div 
            key={name}
            initial={{ opacity: 0, y: 20 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ delay: idx * 0.1 }}
          >
            <Card className="bg-card/50 backdrop-blur h-full flex flex-col hover:border-primary/50 transition-colors relative overflow-hidden">
              <div className="absolute top-0 right-0 p-4 opacity-10">
                <FileSpreadsheet className="w-24 h-24" />
              </div>
              <CardHeader>
                <CardTitle className="text-xl capitalize flex items-center gap-2">
                  <Database className="w-5 h-5 text-primary" />
                  {name.replace(/_/g, ' ')}
                </CardTitle>
              </CardHeader>
              <CardContent className="space-y-4">
                <div className="flex justify-between items-center text-sm border-b border-border/50 pb-2">
                  <span className="text-muted-foreground">Status</span>
                  <span className={`font-medium ${info.status === 'Available' ? 'text-emerald-500' : 'text-destructive'}`}>
                    {info.status}
                  </span>
                </div>
                <div className="flex justify-between items-center text-sm border-b border-border/50 pb-2">
                  <span className="text-muted-foreground">Rows / Events</span>
                  <span className="font-mono font-medium">{info.event_count.toLocaleString()}</span>
                </div>
                <div className="flex justify-between items-center text-sm pb-2">
                  <span className="text-muted-foreground">Format</span>
                  <span className="font-mono text-xs bg-muted px-2 py-1 rounded">CSV</span>
                </div>
              </CardContent>
            </Card>
          </motion.div>
        ))}
      </div>
    </div>
  );
}
